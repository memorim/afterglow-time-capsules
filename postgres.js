import pg from 'pg';
import { basename } from 'node:path';

export function poolOptions(connectionString) {
  const url = new URL(connectionString);
  if (!['postgres:', 'postgresql:'].includes(url.protocol)) throw new Error('PostgreSQL URL required');
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  for (const key of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) url.searchParams.delete(key);
  return { connectionString: url.toString(), ssl: local ? false : { rejectUnauthorized: true },
    max: 4, idleTimeoutMillis: 10000, connectionTimeoutMillis: 15000,
    statement_timeout: 15000 };
}

// One bounded pool, separate server-derived schema per authenticated account.
export function createPostgresFactory(connectionString, { seedDb } = {}) {
  const pool = new pg.Pool(poolOptions(connectionString));
  pool.on('error', () => console.error({ event: 'database_pool_error' }));
  async function open(file) {
    const hash = basename(file, '.db');
    if (!/^[a-f0-9]{64}$/.test(hash)) throw new Error('Account database identifier required');
    // Full digest is retained: PostgreSQL identifiers are limited to 63 bytes.
    const schema = 'ag_' + BigInt('0x' + hash).toString(36);
    const table = '"' + schema + '".capsules';
    const budgets = '"' + schema + '".request_budgets';
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1,0))', [schema]);
      const existed = (await client.query('SELECT to_regclass($1) AS name', [table])).rows[0].name;
      await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);
      await client.query(`CREATE TABLE IF NOT EXISTS ${table} (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title text NOT NULL, sender text NOT NULL, recipient text NOT NULL,
        unlock_at text NOT NULL, theme text NOT NULL, color text NOT NULL,
        hint text NOT NULL, ciphertext text NOT NULL, salt text NOT NULL,
        iv text NOT NULL, tag text NOT NULL, created_at text NOT NULL
      )`);
      await client.query(`CREATE INDEX IF NOT EXISTS capsules_unlock_order ON ${table}(unlock_at,id)`);
      await client.query(`CREATE TABLE IF NOT EXISTS ${budgets}(key text PRIMARY KEY,count integer NOT NULL,reset_at bigint NOT NULL)`);
      if (!existed && seedDb) {
        const seed = seedDb(':memory:');
        try {
          for (const row of seed.prepare('SELECT * FROM capsules ORDER BY id').all()) {
            const fields = ['title','sender','recipient','unlock_at','theme','color','hint','ciphertext','salt','iv','tag','created_at'];
            await client.query(`INSERT INTO ${table}(${fields.join(',')}) VALUES(${fields.map((_,i)=>'$'+(i+1)).join(',')})`, fields.map(f=>row[f]));
          }
        } finally { seed.close(); }
      }
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally { client.release(); }
    return {
      schema,
      prepare(sql) {
        // Only the application's capsule queries use this adapter. No user SQL.
        if (!/^(SELECT \* FROM capsules|INSERT INTO capsules\()/i.test(sql.trim())) throw new Error('Unsupported capsule query');
        let index = 0;
        const query = sql.replace(/\bcapsules\b/g, table).replace(/\?/g, () => '$' + (++index));
        return {
          async all(...values) { return (await pool.query(query, values)).rows; },
          async get(...values) { return (await pool.query(query, values)).rows[0]; },
          async run(...values) {
            const result = await pool.query(query + ' RETURNING id', values);
            return { lastInsertRowid: result.rows[0].id, changes: result.rowCount };
          },
        };
      },
      async consumeBudget(key, maximum, now, windowMs = 60000) {
        const { rows: [row] } = await pool.query(`INSERT INTO ${budgets} AS b(key,count,reset_at) VALUES($1,1,$2)
          ON CONFLICT(key) DO UPDATE SET count=CASE WHEN b.reset_at<=$3 THEN 1 ELSE LEAST(b.count+1,$4) END,
          reset_at=CASE WHEN b.reset_at<=$3 THEN excluded.reset_at ELSE b.reset_at END RETURNING count,reset_at`,
        [key, now+windowMs, now, maximum+1]);
        return { allowed: row.count <= maximum, retryAfter: Math.max(1, Math.ceil((Number(row.reset_at)-now)/1000)) };
      },
      async purgeExpired({ now = Date.now(), retentionDays = 365 } = {}) {
        if (!Number.isInteger(retentionDays) || retentionDays < 1 || retentionDays > 3650) throw new Error('Retention must be 1–3650 days after unlock');
        // Legacy seed timestamps without an offset are UTC, matching SQLite.
        return (await pool.query(`DELETE FROM ${table} WHERE
          (CASE WHEN unlock_at ~ '(Z|[+-][0-9]{2}:[0-9]{2})$' THEN unlock_at ELSE unlock_at || 'Z' END)::timestamptz <= $1::timestamptz`,
        [new Date(now-retentionDays*86400000).toISOString()])).rowCount;
      },
      close() {},
    };
  }
  return { open, close: () => pool.end() };
}
